<?php
/**
 * Generate src/WebhookEvents.php from the vendored core's event constants
 * (CreateWebhookEndpointRequest::EVENTS_*). Catalog auto-syncs with the spec on
 * each scripts/sync_core.php.
 *
 * Run: php scripts/gen_webhook_events.php
 */

$repo = dirname(__DIR__);
$src = $repo . '/lib/Model/CreateWebhookEndpointRequest.php';
$out = $repo . '/src/WebhookEvents.php';

$code = file_get_contents($src);
preg_match_all("/EVENTS_[A-Z0-9_]+\s*=\s*'([^']+)'/", $code, $m);
$values = $m[1];
if (!$values) {
    fwrite(STDERR, "no event constants parsed from $src\n");
    exit(1);
}
$values = array_values(array_unique($values));

$items = implode("\n", array_map(fn($v) => "        '$v',", $values));

$php = <<<PHP
<?php

declare(strict_types=1);

namespace Selectwin;

/**
 * GENERATED by scripts/gen_webhook_events.php — DO NOT EDIT.
 *
 * The authoritative webhook Event Catalog — every value a webhook endpoint's
 * `events[]` accepts. Regenerate after scripts/sync_core.php.
 */
final class WebhookEvents
{
    /** @var list<string> */
    public const ALL = [
$items
    ];

    /** Is \$type one of the known webhook event types? */
    public static function isValid(string \$type): bool
    {
        return in_array(\$type, self::ALL, true);
    }
}

PHP;

file_put_contents($out, $php);
echo "wrote src/WebhookEvents.php — " . count($values) . " event types\n";
